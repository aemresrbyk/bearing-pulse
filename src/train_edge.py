"""Phase 4: train a small Random Forest on edge features and export it as C for the ESP32.

    python src/train_edge.py

Until my own fan data exists (Phase 3, needs hardware), the training data is CWRU passed through
an ADXL345 model (3200 Hz, ±16 g, 3.9 mg steps). Re-run with own data later; the export stays the same.
"""
import sys
from pathlib import Path

import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bearing  # noqa: E402
import edge  # noqa: E402

OUT = edge.C_DIR / "model.c"
N_TREES, MAX_DEPTH = 10, 6   # small enough to be a few kB of code on the ESP32


def dataset(loads):
    X, y, pos = [], [], []
    for num, (cond, load) in bearing.FILES.items():
        if load not in loads:
            continue
        x = edge.adxl345(bearing.load(num)[0])
        n = len(x) // edge.WINDOW
        X += [edge.features(w) for w in x[: n * edge.WINDOW].reshape(n, edge.WINDOW)]
        y += [edge.CLASSES.index(cond)] * n
        pos += list(np.arange(n) / n)
    return np.array(X), np.array(y), np.array(pos)


def tree_to_c(tree, t):
    """One sklearn tree -> nested if/else that adds the leaf's class distribution to prob[]."""
    s = tree.tree_
    lines = []

    def node(i, depth):
        pad = "    " * depth
        if s.children_left[i] == -1:                       # leaf
            v = s.value[i][0] / s.value[i][0].sum()
            lines.extend(f"{pad}prob[{k}] += {float(p)!r}f;" for k, p in enumerate(v) if p > 0)
            return
        # sklearn compares the float32 feature against a float64 threshold; a double literal does the same
        lines.append(f"{pad}if (feat[{s.feature[i]}] <= {float(s.threshold[i])!r}) {{")
        node(s.children_left[i], depth + 1)
        lines.append(f"{pad}}} else {{")
        node(s.children_right[i], depth + 1)
        lines.append(f"{pad}}}")

    node(0, 1)
    return f"static void tree{t}(const float *feat, float *prob) {{\n" + "\n".join(lines) + "\n}\n"


def export(clf):
    body = "\n".join(tree_to_c(est, t) for t, est in enumerate(clf.estimators_))
    calls = "\n".join(f"    tree{t}(feat, prob);" for t in range(len(clf.estimators_)))
    OUT.write_text(f"""// GENERATED by src/train_edge.py — do not edit by hand.
// Random Forest: {len(clf.estimators_)} trees, max depth {MAX_DEPTH}, features: {", ".join(edge.FEATURE_NAMES)}
// Classes: {", ".join(edge.CLASSES)}
#include "bearing_edge.h"

{body}
int be_predict(const float *feat, float *prob) {{
    for (int k = 0; k < BE_N_CLASS; k++) prob[k] = 0;
{calls}
    int best = 0;
    for (int k = 0; k < BE_N_CLASS; k++) {{
        prob[k] /= {len(clf.estimators_)};
        if (prob[k] > prob[best]) best = k;
    }}
    return best;
}}
""")


if __name__ == "__main__":
    data = {load: dataset([load]) for load in range(4)}
    # Honest estimate: leave one load out. Training on 0 HP only gave 74 / 80 / 47 % on 1 / 2 / 3 HP —
    # at 3200 Hz the fault signature is weaker and load changes matter more than at 12 kHz.
    accs = []
    for held in range(4):
        X = np.vstack([data[l][0] for l in range(4) if l != held])
        y = np.concatenate([data[l][1] for l in range(4) if l != held])
        clf = RandomForestClassifier(N_TREES, max_depth=MAX_DEPTH, random_state=0).fit(X, y)
        p = clf.predict_proba(data[held][0])
        accs.append(accuracy_score(data[held][1], p.argmax(1)))
        print(f"held-out {held} HP: accuracy {accs[-1]:.3f}, mean confidence {p.max(1).mean():.2f}")
    print(f"leave-one-load-out mean: {np.mean(accs):.3f}")
    # Device model: all four loads
    X = np.vstack([d[0] for d in data.values()])
    y = np.concatenate([d[1] for d in data.values()])
    clf = RandomForestClassifier(N_TREES, max_depth=MAX_DEPTH, random_state=0).fit(X, y)
    export(clf)
    np.savez(edge.ROOT / ".local" / "edge_testset.npz", X=X, y=y, proba=clf.predict_proba(X))
    print(f"wrote {OUT.relative_to(edge.ROOT)} ({OUT.stat().st_size / 1024:.1f} kB of C)")
